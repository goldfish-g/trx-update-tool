// Copies the files the converter takes as TRX ships them:
//
// - the game scripts of TR1, TR2 and TR3, into client/src/converter/lua/base.
//   A converted game that brings a game script of its own replaces the one of
//   the game it extends, which is where TRX sets up the interface, the water
//   colors and the save crystals, so the converter runs both.
// - cfg/outfits.json5, into client/src/templates/cfg. A game's outfits file
//   replaces the shipped one, so the outfit made of a level's own meshes is
//   written beside the shipped outfits as they stand.
// - the files a game's own copies are merged into, the names of the shipped
//   injections and the font of TR1-3, into client/src/templates/base.
//
// Usage: node scripts/copy-trx-files.mjs [path to TRX]

import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const trx = process.argv[2] ?? '../TRX';
const ship = join(trx, 'data/trx/ship');

const scripts = 'client/src/converter/lua/base';
mkdirSync(scripts, { recursive: true });
for (const game of ['tr1', 'tr2', 'tr3', 'tr3-la']) {
    copyFileSync(join(ship, 'games', game, 'scripts/_game.lua'), join(scripts, `${game}_game.lua`));
}
copyFileSync(join(ship, 'cfg/outfits.json5'), 'client/src/templates/cfg/outfits.json5');
console.log('copied the TR1-3 and TR3:LA game scripts and cfg/outfits.json5');

// The files a game's own copies are merged into: what TRX ships for each game
// now, so the merge keeps what TRX has added since the copy was made.
const BASE_FILES = [
    'weapons.json5',
    'inv_ring.json5',
    'catalog_objects.csv',
    'catalog_samples.csv',
    'catalog_music.csv',
    'catalog_lara_states.csv',
    'catalog_lara_anims.csv',
    'catalog_item_actions.csv',
];
const base = 'client/src/templates/base';
const imports = [];
const entries = [];
for (const game of ['tr1', 'tr2', 'tr3']) {
    mkdirSync(join(base, game), { recursive: true });
    for (const file of BASE_FILES) {
        copyFileSync(join(ship, 'games', game, file), join(base, game, file));
        const name = `${game}_${file.replace(/\W/g, '_')}`;
        imports.push(`import ${name} from './${game}/${file}?raw';`);
        entries.push(`    '${game}/${file}': ${name},`);
    }
}
const injections = ['tr1', 'tr2', 'tr3'].map((game) =>
    `    ${game}: ${JSON.stringify(readdirSync(join(ship, 'games', game, 'injections')).filter((f) => f.endsWith('.bin')).sort())},`);
// Every object the engine knows, by the name a catalog gives it: a game's
// own catalog may name any of them, those of the other games among them.
const objectNames = [...readFileSync(join(trx, 'src/trx/game/catalog/objects.def'), 'utf8').matchAll(/X_CATALOG_ID\(O_(\w+)\)/g)]
    .map((m) => m[1].toLowerCase()).sort();
writeFileSync(join(base, 'index.ts'), [
    '// Generated by scripts/copy-trx-files.mjs. Do not edit.',
    ...imports,
    '',
    '/** What TRX ships for each game, by "<game>/<file>". */',
    'export const BASE_FILES: Record<string, string> = {',
    ...entries,
    '};',
    '',
    '/** The injections TRX ships for each game. */',
    'export const BASE_INJECTIONS: Record<string, string[]> = {',
    ...injections,
    '};',
    '',
    '/** Every object the engine knows, by the name a catalog gives it. */',
    `export const OBJECT_NAMES: string[] = ${JSON.stringify(objectNames)};`,
    '',
].join('\n'));
console.log(`copied ${BASE_FILES.length} files for each of TR1-3`);

// TRX's font, which the converter rebuilds with the sprites a level builder
// redrew (font.ts). Loaded only for such a game, so it has a module of its own.
const fonts = ['tr1', 'tr2', 'tr3'].map((game) =>
    `    ${game}: '${readFileSync(join(ship, 'games', game, 'injections/font.bin')).toString('base64')}',`);
writeFileSync(join(base, 'fonts.ts'), [
    '// Generated by scripts/copy-trx-files.mjs. Do not edit.',
    '',
    '/** TRX\'s injections/font.bin of each game, in base64. */',
    'export const BASE_FONTS: Record<string, string> = {',
    ...fonts,
    '};',
    '',
].join('\n'));
console.log('copied the font of each of TR1-3');

// The level scripts TRX ships for each game, which a game that brings a copy
// of one as TRX had it gets as TRX has it now (lua.ts): TRX runs only the
// game's own, never those of the game it extends. Loaded only for such a game.
const levelScripts = [];
for (const game of ['tr1', 'tr2', 'tr3']) {
    for (const name of readdirSync(join(ship, 'games', game, 'scripts')).filter((f) => f.endsWith('.lua') && f !== '_game.lua').sort()) {
        levelScripts.push(`    '${game}/${name}': ${JSON.stringify(readFileSync(join(ship, 'games', game, 'scripts', name), 'utf8'))},`);
    }
}
writeFileSync(join(base, 'level_scripts.ts'), [
    '// Generated by scripts/copy-trx-files.mjs. Do not edit.',
    '',
    '/** The level scripts TRX ships for TR1-3, by "<game>/<file>". */',
    'export const BASE_LEVEL_SCRIPTS: Record<string, string> = {',
    ...levelScripts,
    '};',
    '',
].join('\n'));
console.log(`copied ${levelScripts.length} level scripts of TR1-3`);
