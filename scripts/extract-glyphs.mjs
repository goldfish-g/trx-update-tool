// Writes client/src/converter/glyphs.generated.ts, for the converter to
// rebuild TRX's font with the sprites a level builder redrew (font.ts):
//
// - what each sprite of the font of TR1, TR2 and TR3 looks like in the games'
//   own levels, so that the converter can tell the builder's;
// - the characters TRX's glyph tools make of two others, a letter and an
//   accent (combine() in TRX's data/tr1/glyphs/mapping*.txt), by the places
//   text_autogen.def gives them, so that a redrawn letter or accent is
//   combined again as tools/shared/glyph_mapping.py combines them.
//
// Usage: node scripts/extract-glyphs.mjs [--trx <path to TRX>] <level file, directory or .zip>...
// Give it every level of the original games and of their expansions; a game
// whose title level draws some sprites apart (TR2's) gets both.
// Runs on Node 23.6 or later, which reads the converter's TypeScript.

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { unzipSync } from 'fflate';
import { glyphFingerprint, readAlphabet } from '../client/src/converter/level.ts';

/** Two looks of one shape this close in every channel are kept as one. */
const SAME_COLOUR = 12;

const args = process.argv.slice(2);
let trx = '../TRX';
if (args[0] === '--trx') {
    trx = args[1];
    args.splice(0, 2);
}

// The places of TRX's glyphs, by their text.
const places = new Map();
for (const m of readFileSync(join(trx, 'src/trx/game/ui/text_autogen.def'), 'utf8').matchAll(/^X_GLYPH_DEFINE\(("(?:[^"\\]|\\.)*"), \w+, (\d+)\)/gm)) {
    places.set(JSON.parse(m[1]), Number(m[2]));
}
// A glyph's text in mapping.txt: U+XXXX:c or a quoted string.
const text = (token) => (token.startsWith('U+') ? String.fromCodePoint(parseInt(token.slice(2, 6), 16)) : JSON.parse(token));
const TOKEN = String.raw`(U\+[0-9A-F]{4}:.|"(?:[^"\\]|\\.)*")`;
const COMBINE = new RegExp(String.raw`^${TOKEN} 0 C combine\(${TOKEN}, ${TOKEN}((?:, \w+=[^,)]+)*)\)\s*$`);
const combined = [];
const glyphDir = join(trx, 'data/tr1/glyphs');
const readMapping = (name) => {
    for (const line of readFileSync(join(glyphDir, name), 'utf8').split('\n')) {
        const include = /^include "([^"]+)"/.exec(line);
        if (include) {
            readMapping(include[1]);
            continue;
        }
        const m = COMBINE.exec(line);
        if (!m) {
            if (/ combine\(/.test(line) && !line.startsWith('#') && / 0 C /.test(line)) throw new Error(`unread combine(): ${line}`);
            continue;
        }
        const options = Object.fromEntries([...m[4].matchAll(/(\w+)=([^,)]+)/g)].map(([, key, value]) => [key, value.startsWith('"') ? JSON.parse(value) : Number(value)]));
        const [place, letter, accent] = [m[1], m[2], m[3]].map((token) => places.get(text(token)));
        if (place === undefined || letter === undefined || accent === undefined) throw new Error(`no place for ${line}`);
        combined.push([place, letter, accent, options.offset_x ?? 0, options.offset_y ?? 0, options.align ?? 'top']);
    }
};
readMapping('mapping.txt');

const levels = [];
const add = (name, data) => {
    if (/\.(phd|tr2)$/i.test(name)) levels.push({ name, data });
};
const walk = (path) => {
    if (statSync(path).isDirectory()) {
        for (const entry of readdirSync(path)) walk(join(path, entry));
    } else if (/\.zip$/i.test(path)) {
        for (const [name, data] of Object.entries(unzipSync(readFileSync(path)))) add(`${path}:${name}`, data);
    } else {
        add(path, new Uint8Array(readFileSync(path)));
    }
};
for (const path of args) walk(path);

const games = { 1: [], 2: [], 3: [] };
const read = { 1: 0, 2: 0, 3: 0 };
for (const { name, data } of levels) {
    const alphabet = readAlphabet(data);
    if (!alphabet) {
        console.warn(`skipped ${name}: no font read`);
        continue;
    }
    read[alphabet.gameVersion]++;
    const glyphs = games[alphabet.gameVersion];
    alphabet.glyphs.forEach((glyph, i) => {
        const looks = (glyphs[i] ??= []);
        const print = glyphFingerprint(glyph);
        if (!print) return;
        const known = looks.some((look) => look.shape === print.shape && look.colour.every((c, k) => Math.abs(c - print.colour[k]) <= SAME_COLOUR));
        if (!known) looks.push(print);
    });
}

const hex = (colour) => colour.map((c) => c.toString(16).padStart(2, '0')).join('');
const lines = [
    '// Generated by scripts/extract-glyphs.mjs from the levels of TR1, TR2 and TR3',
    '// and their expansions. Do not edit.',
    '',
    '/**',
    ' * The sprites of each game\'s own font, by their place in it: how each looks',
    ' * in the game\'s levels, as "<shape> <colour>" (glyphFingerprint in level.ts).',
    ' */',
    'export const STOCK_GLYPHS: Record<number, string[][]> = {',
];
for (const [game, glyphs] of Object.entries(games)) {
    if (glyphs.length === 0) continue;
    lines.push(`    ${game}: [`);
    for (const looks of glyphs) lines.push(`        [${looks.map((look) => `'${look.shape} ${hex(look.colour)}'`).join(', ')}],`);
    lines.push('    ],');
}
lines.push(
    '};',
    '',
    '/**',
    ' * The sprites TRX\'s glyph tools make of a letter and an accent, the same in',
    ' * every game: [place, letter\'s place, accent\'s place, offset_x, offset_y, align],',
    ' * in the order the tools make them.',
    ' */',
    'export const COMBINED_GLYPHS: [number, number, number, number, number, string][] = [',
    ...combined.map((entry) => `    ${JSON.stringify(entry).replace(/,/g, ', ').replace(/"/g, "'")},`),
    '];',
    '',
);
writeFileSync('client/src/converter/glyphs.generated.ts', lines.join('\n'));
console.log(`read the fonts of ${read[1]} TR1, ${read[2]} TR2 and ${read[3]} TR3 levels, and ${combined.length} combined characters`);
