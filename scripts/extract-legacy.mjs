// Writes client/src/converter/legacy.generated.ts from TRX's git history:
//
// - LEGACY_STRING_IDS: the game string ids of Tomb1Main, TR1X and TR2X
//   (once Tomb2Main), the engines before TRX, by the TRX 1.3 id that has
//   the same text, which
//   GAME_STRING_IDS (history.generated.ts) then takes to the current path.
//   Games made for those engines rename strings by these ids in their game
//   flows and strings files.
//
// The ids and their texts come from every TR1X and TR2X release: their
// game_string.def files, and before those existed, the strings the shipped
// game flows carried.
//
// Usage: node scripts/extract-legacy.mjs [path to TRX]

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const trx = process.argv[2] ?? '../TRX';
const git = (...args) => execFileSync('git', ['-C', trx, ...args], { encoding: 'utf8', maxBuffer: 1 << 28 });

// JSON5 read leniently: comments and trailing commas.
const parse = (text) => {
    try {
        return JSON.parse(text.replace(/^\s*\/\/.*$/gm, '').replace(/,\s*([\]}])/g, '$1'));
    } catch {
        return null;
    }
};
const show = (ref, path) => {
    try {
        return git('show', `${ref}:${path}`);
    } catch {
        return null;
    }
};

const LEGACY_TAG = /^(tr1|tr2)-\d/;
const DEF = /(^|\/)game_string\.def$/;
const SHIPPED = /(^|\/)cfg\/(tomb[123]main|tr1x|tr2x)_(gameflow|strings)[^/]*\.json5$/i;
const GS_DEFINE = /^\s*GS_DEFINE\((\w+),\s*"((?:[^"\\]|\\.)*)"\)/gm;

/** Every text each legacy id has had. */
const legacy = new Map();
const note = (id, text) => {
    if (typeof text !== 'string') return;
    if (!legacy.has(id)) legacy.set(id, new Set());
    legacy.get(id).add(text);
};

const tags = git('tag', '-l').split('\n').filter((tag) => LEGACY_TAG.test(tag));
for (const tag of tags) {
    for (const path of git('ls-tree', '-r', '--name-only', tag).split('\n')) {
        if (DEF.test(path)) {
            for (const [, id, text] of (show(tag, path) ?? '').matchAll(GS_DEFINE)) note(id, JSON.parse(`"${text}"`));
        } else if (SHIPPED.test(path)) {
            const doc = parse(show(tag, path) ?? '');
            for (const key of ['strings', 'game_strings']) {
                if (doc && doc[key] && typeof doc[key] === 'object') {
                    for (const [id, text] of Object.entries(doc[key])) note(id, text);
                }
            }
        }
    }
}

// TRX 1.3's ids and their texts, as GAME_STRING_IDS takes them.
const current = new Map();
for (const path of ['data/common/ship/cfg/base_strings.json5', 'data/tr1/ship/cfg/tr1/strings.json5', 'data/tr2/ship/cfg/tr2/strings.json5']) {
    const doc = parse(show('trx-1.3', path) ?? '');
    for (const [id, text] of Object.entries(doc?.game_strings ?? {})) current.set(id, text);
}
// Only texts with words tell strings apart; "%d" or "On" name many.
const telling = (text) => (text.match(/[A-Za-z]/g) ?? []).length >= 4;
const byText = new Map();
for (const [id, text] of current) if (telling(text) && !byText.has(text)) byText.set(text, id);

const ids = {};
for (const [id, texts] of legacy) {
    if (current.has(id)) {
        ids[id] = id;
        continue;
    }
    for (const text of texts) {
        const match = byText.get(text);
        if (match !== undefined) {
            ids[id] = match;
            break;
        }
    }
}

const lines = [
    "// Generated by scripts/extract-legacy.mjs from TRX's git history.",
    '// Do not edit; run the script again against a newer TRX.',
    '',
    '/** Tomb1Main, TR1X and TR2X string ids, by the TRX 1.3 id of the same text. */',
    'export const LEGACY_STRING_IDS: Record<string, string> = {',
    ...Object.keys(ids).sort().map((id) => `    ${JSON.stringify(id)}: ${JSON.stringify(ids[id])},`),
    '};',
    '',
];
writeFileSync('client/src/converter/legacy.generated.ts', lines.join('\n'));
console.log(`legacy string ids: ${Object.keys(ids).length} of ${legacy.size} from ${tags.length} releases`);
const unmatched = [...legacy.keys()].filter((id) => !(id in ids) && !id.startsWith('INV_ITEM_'));
console.log(`no TRX 1.3 match: ${unmatched.length}`, unmatched.slice(0, 40).join(' '));
