// Writes client/src/converter/renames.generated.ts from TRX's migration guide
// (docs/trx/MIGRATING.md), so the converter renames what TRX renamed, one for
// one, and nothing it would have to guess at.
//
// Usage: node scripts/extract-renames.mjs [path to TRX]

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const trx = process.argv[2] ?? '../TRX';
const lines = readFileSync(join(trx, 'docs/trx/MIGRATING.md'), 'utf8').split('\n');

const objectKeys = {};
const objectSymbols = {};
const luaApi = {};
let section = '';
let item = '';
let subsection = '';

// A code cell names one thing when it is a plain name or a dotted path.
const plainName = /^[A-Za-z_][\w.:]*(\(\))?$/;

for (const line of lines) {
    if (line.startsWith('## ')) section = line;
    if (line.startsWith('### ')) {
        item = '';
        subsection = '';
    }
    const heading = /^\d+\. \*\*(.+)\*\*/.exec(line.trim());
    if (heading) {
        item = heading[1];
        subsection = '';
    }
    if (line.startsWith('#### ')) subsection = line.slice(5).trim();
    if (section !== '## TRX') continue;

    const row = /^\s*\| `([^`]+)`\s*\| `([^`]+)`\s*\|\s*$/.exec(line);
    if (!row) continue;
    const [, was, now] = row;
    if (!plainName.test(was) || !plainName.test(now)) continue;

    if (item.startsWith("An object's key is its C spelling")) {
        objectKeys[was] = now;
    } else if (item.startsWith('Some objects were renamed')) {
        objectSymbols[was] = now;
    } else if (subsection === 'Renamed') {
        luaApi[was] = now;
    }
}

const table = (name, doc, entries) =>
    `/** ${doc} */\nexport const ${name}: Record<string, string> = {\n` +
    Object.entries(entries)
        .map(([was, now]) => `    ${JSON.stringify(was)}: ${JSON.stringify(now)},`)
        .join('\n') +
    '\n};\n';

writeFileSync(
    'client/src/converter/renames.generated.ts',
    '// Generated by scripts/extract-renames.mjs from TRX\'s docs/trx/MIGRATING.md.\n' +
        '// Do not edit; run the script again when TRX renames more.\n\n' +
        table('OBJECT_KEYS', 'Object keys, as game flows, strings and Lua name them.', objectKeys) +
        '\n' +
        table('OBJECT_SYMBOLS', 'Object symbols, as catalogs spell them.', objectSymbols) +
        '\n' +
        table('LUA_API', 'Lua API names renamed one for one.', luaApi),
);
console.log(
    `object keys: ${Object.keys(objectKeys).length}, object symbols: ${Object.keys(objectSymbols).length}, ` +
        `Lua API: ${Object.keys(luaApi).length}`,
);
