// Lists the pictures TRX ships for its games, by their contents, into
// client/src/converter/stockpictures.generated.ts: each file name with the
// ids git would give each version of it, cut to 16 hex digits as
// history.generated.ts keeps them. TRX's pictures are not in its repository;
// tools/download_assets fetches them into data/trx/ship, and an engine build
// packs them from there.
//
// Usage: node scripts/extract-stock-pictures.mjs <ship dir>, a directory
// laid out as games/<game>/images/..., such as TRX's data/trx/ship after
// tools/download_assets, or an engine build's packed files unpacked.

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [shipDir] = process.argv.slice(2);
if (!shipDir) throw new Error('usage: node scripts/extract-stock-pictures.mjs <ship dir>');

const walk = (dir) => readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => (entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)]));
const blobId = (data) => createHash('sha1').update(`blob ${data.length}\0`).update(data).digest('hex').slice(0, 16);

const pictures = {};
let count = 0;
for (const game of readdirSync(join(shipDir, 'games')).sort()) {
    let files;
    try {
        files = walk(join(shipDir, 'games', game, 'images'));
    } catch {
        continue;
    }
    for (const file of files) {
        const name = file.slice(file.lastIndexOf('/') + 1).toLowerCase();
        const id = blobId(readFileSync(file));
        const ids = (pictures[name] ??= []);
        if (!ids.includes(id)) ids.push(id);
        count++;
    }
}
const sorted = Object.fromEntries(Object.entries(pictures).sort(([a], [b]) => a.localeCompare(b)).map(([name, ids]) => [name, ids.sort()]));

writeFileSync('client/src/converter/stockpictures.generated.ts', [
    '// Generated by scripts/extract-stock-pictures.mjs. Do not edit.',
    '',
    '/** The pictures TRX ships for its games, every version of each, by file name. */',
    `export const STOCK_PICTURES: Record<string, string[]> = ${JSON.stringify(sorted)};`,
    '',
].join('\n'));
console.log(`${count} pictures, ${Object.keys(sorted).length} names`);
