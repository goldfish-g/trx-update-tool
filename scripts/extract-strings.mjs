// Writes client/src/converter/strings.generated.ts from TRX's git history:
// STOCK_STRINGS, for every engine-wide game string the current TRX has
// (cfg/base_strings*.json5, TRX_common_strings*.json5 up to 1.3), a hash of
// every text any build ever gave it, in any language. A builder's copy of
// those files that gives a string a text none of them did holds the
// builder's edit (client/src/converter/strings.ts).
//
// Usage: node scripts/extract-strings.mjs [path to TRX]

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { currentObjectKey } from '../client/src/converter/objects.ts';
import { flattenStrings, textHash } from '../client/src/converter/strings.ts';

const trx = process.argv[2] ?? '../TRX';
const git = (...args) => execFileSync('git', ['-C', trx, ...args], { encoding: 'utf8', maxBuffer: 1 << 30 });

const FILE = /(^|\/)cfg\/(base_strings|trx_common_strings)(-[a-z0-9-]+)?\.json5$/i;
// JSON5 read leniently, as extract-history.mjs does.
const parse = (text) => JSON.parse(text.replace(/^\s*\/\/.*$/gm, '').replace(/,\s*([\]}])/g, '$1'));

// The strings the current TRX has.
const current = new Set();
for (const line of git('ls-tree', '-r', 'HEAD', '--', 'data/trx/ship/cfg').split('\n')) {
    const m = /^\d+ blob ([0-9a-f]{40})\t(.+)$/.exec(line);
    if (m && FILE.test(m[2])) for (const path of flattenStrings(parse(git('cat-file', '-p', m[1]))).keys()) current.add(path);
}
// Every version of the files any commit has held: branches, tags and remotes, no stash.
const blobs = new Set();
const log = git('log', '--branches', '--tags', '--remotes', '--root', '-m', '--no-renames', '--raw', '--no-abbrev', '--format=', '--', 'data');
for (const line of log.split('\n')) {
    const m = /^:\d+ \d+ [0-9a-f]{40} ([0-9a-f]{40}) [A-Z]\d*\t(.+)$/.exec(line);
    if (m && !/^0+$/.test(m[1]) && FILE.test(m[2])) blobs.add(m[1]);
}
const texts = {};
let read = 0;
for (const blob of blobs) {
    let doc;
    try {
        doc = parse(git('cat-file', '-p', blob));
    } catch {
        continue;
    }
    read++;
    for (const [path, text] of flattenStrings(doc)) {
        // An object's strings under the key it has now too, as strings.ts
        // reads a builder's copy of a build that named it otherwise.
        const paths = new Set([path]);
        const object = /^objects\/([^/]+)\/(.+)$/.exec(path);
        if (object) {
            for (const game of [1, 2, 3]) {
                const key = currentObjectKey(object[1], 0, game);
                if (key !== null) paths.add(`objects/${key}/${object[2]}`);
            }
        }
        for (const now of paths) if (current.has(now)) (texts[now] ??= new Set()).add(textHash(text));
    }
}
const lines = [
    "// Generated by scripts/extract-strings.mjs from TRX's git history.",
    '// Do not edit; run the script again against a newer TRX.',
    '',
    '/** Every engine-wide game string the current TRX has, with a hash of each text any build gave it (strings.ts textHash). */',
    'export const STOCK_STRINGS: Record<string, string[]> = {',
    ...Object.keys(texts).sort().map((p) => `    ${JSON.stringify(p)}: ${JSON.stringify([...texts[p]].sort())},`),
    '};',
    '',
];
writeFileSync('client/src/converter/strings.generated.ts', lines.join('\n'));
const total = Object.values(texts).reduce((n, s) => n + s.size, 0);
console.log(`strings files: ${read} of ${blobs.size} versions read; ${current.size} current strings, ${total} texts`);
