// Writes client/src/converter/stockfields.generated.ts from TRX's git history,
// what TRX's own data files held in each release, which tells what a game's
// copy of one leaves out on purpose:
//
// - STOCK_WEAPON_FIELDS: for each game and each release from 1.10, the
//   weapons and fields of weapons.json5 in any build of that release. From
//   1.10 a game's weapons file is all the engine reads (weapons.ts).
// - STOCK_RING_OBJECTS: for each game and release, the objects
//   inv_ring.json5 put on the ring. A game's ring file is all the engine
//   reads, in every TRX (ring.ts).
//
// Usage: node scripts/extract-stock-fields.mjs [path to TRX]

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { parseJSON5 } from '../client/src/converter/json5.ts';
import { currentObjectKey } from '../client/src/converter/objects.ts';
import { currentWeapon, isFlatWeapon, weaponFields } from '../client/src/converter/weapons.ts';

const trx = process.argv[2] ?? '../TRX';
const git = (...args) => execFileSync('git', ['-C', trx, ...args], { encoding: 'utf8', maxBuffer: 1 << 30 });
const show = (tag, paths) => {
    for (const path of paths) {
        try {
            return git('show', `${tag}:${path}`);
        } catch {
            // Not where this release kept it.
        }
    }
    return null;
};

const weapons = {};
const rings = {};
for (const tag of git('tag', '--list', 'trx-1.*').split('\n').filter(Boolean)) {
    const m = /^trx-1\.(\d+)(?:\.\d+)*$/.exec(tag);
    if (!m) continue;
    const release = Number(m[1]);
    for (const game of [1, 2, 3]) {
        const ring = show(tag, [`data/trx/ship/games/tr${game}/inv_ring.json5`, `data/tr${game}/ship/cfg/inv_ring.json5`]);
        if (ring !== null) {
            const set = ((rings[`tr${game}`] ??= {})[release] ??= new Set());
            for (const entry of parseJSON5(ring)) {
                const key = typeof entry.object_id === 'string' ? currentObjectKey(entry.object_id, release, game) : null;
                if (key !== null) set.add(key);
            }
        }
        if (release < 10) continue;
        const text = show(tag, [`data/trx/ship/games/tr${game}/weapons.json5`]);
        if (text === null) continue;
        const set = ((weapons[`tr${game}`] ??= {})[release] ??= new Set());
        for (const [rawKey, weapon] of Object.entries(parseJSON5(text))) {
            const key = rawKey.replace(/^LGT_/, '').toLowerCase();
            set.add(key);
            const current = release < 11 || isFlatWeapon(weapon) ? currentWeapon(weapon, release, game) : weapon;
            for (const path of weaponFields(current).keys()) set.add(`${key}/${path}`);
        }
    }
}

const table = (name, doc, type, fields) => {
    const lines = [`/** ${doc} */`, `export const ${name}: ${type} = {`];
    for (const game of Object.keys(fields).sort()) {
        lines.push(`    ${game}: {`);
        for (const release of Object.keys(fields[game]).map(Number).sort((a, b) => a - b)) {
            lines.push(`        ${release}: ${JSON.stringify([...fields[game][release]].sort())},`);
        }
        lines.push('    },');
    }
    lines.push('};', '');
    return lines;
};
writeFileSync('client/src/converter/stockfields.generated.ts', [
    "// Generated by scripts/extract-stock-fields.mjs from TRX's git history.",
    '// Do not edit; run the script again against a newer TRX.',
    '',
    'export type StockFields = Record<string, Record<number, string[]>>;',
    '',
    ...table('STOCK_WEAPON_FIELDS', "The weapons and fields TRX's own weapons.json5 had, by game and release (weapons.ts).", 'StockFields', weapons),
    ...table('STOCK_RING_OBJECTS', "The objects TRX's own inv_ring.json5 put on the ring, by game and release (ring.ts).", 'StockFields', rings),
].join('\n'));
for (const [name, fields] of [['weapons', weapons], ['ring', rings]]) {
    for (const game of Object.keys(fields).sort()) {
        console.log(name, game, Object.entries(fields[game]).map(([r, s]) => `1.${r}: ${s.size}`).join(', '));
    }
}
