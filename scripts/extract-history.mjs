// Writes client/src/converter/history.generated.ts from TRX's git history:
//
// - STOCK_BLOBS: the git blob id of every injection, catalog, weapons,
//   inventory ring, outfits and settings preset file and script TRX has shipped, by file
//   name. Level builders copy these into their games, and a copy left as it
//   was is better served by the TRX the game now runs on than by the build it
//   came from.
// - GAME_STRING_IDS: the flat string ids of TRX 1.3 and before, by the path
//   the current strings files give the same text.
//
// Usage: node scripts/extract-history.mjs [path to TRX]

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const trx = process.argv[2] ?? '../TRX';
const git = (...args) => execFileSync('git', ['-C', trx, ...args], { encoding: 'utf8', maxBuffer: 1 << 28 });

const STOCK = /(^|\/)(injections\/[^/]+\.bin|catalog_[a-z_]+\.csv|weapons\.json5|inv_ring\.json5|cfg\/outfits\.json5|cfg\/presets\/[^/]+\.json5|scripts\/[^/]+\.lua)$/;

// Every version any commit has held, not only the releases': builders play
// development builds too (TRX 1.10.2-304-g1f5f941, say) and ship the files
// those had. Branches, tags and remotes, but no stash.
const blobs = {};
const add = (blob, path) => {
    if (!STOCK.test(path) || /^0+$/.test(blob)) return;
    const name = path.split('/').pop().toLowerCase();
    // Sixteen hex digits tell the few thousand versions apart.
    (blobs[name] ??= new Set()).add(blob.slice(0, 16));
};
const log = git('log', '--branches', '--tags', '--remotes', '--root', '-m', '--no-renames', '--raw', '--no-abbrev', '--format=', '--', 'data');
for (const line of log.split('\n')) {
    const m = /^:\d+ \d+ [0-9a-f]{40} ([0-9a-f]{40}) [A-Z]\d*\t(.+)$/.exec(line);
    if (m) add(m[1], m[2]);
}
for (const line of git('ls-tree', '-r', 'HEAD', '--', 'data').split('\n')) {
    const m = /^\d+ blob ([0-9a-f]{40})\t(.+)$/.exec(line);
    if (m) add(m[1], m[2]);
}

// Strings: JSON5 read leniently, then flattened to slash paths.
const parse = (text) => JSON.parse(
    text.replace(/^\s*\/\/.*$/gm, '').replace(/,\s*([\]}])/g, '$1'),
);
function flatten(obj, prefix, out) {
    for (const [key, value] of Object.entries(obj)) {
        const path = prefix ? `${prefix}/${key}` : key;
        if (value && typeof value === 'object' && !Array.isArray(value)) flatten(value, path, out);
        else if (typeof value === 'string') out[path] = value;
    }
    return out;
}
const show = (ref, path) => {
    try {
        return parse(git('show', `${ref}:${path}`));
    } catch {
        return null;
    }
};
const SKIP = new Set(['levels', 'cutscenes', 'demos', 'objects', 'language_name']);
function strings(ref, paths) {
    const out = {};
    for (const path of paths) {
        const doc = show(ref, path);
        if (!doc) continue;
        for (const key of Object.keys(doc)) {
            if (!SKIP.has(key) && doc[key] && typeof doc[key] === 'object') flatten(doc[key], key, out);
        }
    }
    return out;
}
const oldIds = {};
for (const path of ['data/common/ship/cfg/base_strings.json5', 'data/tr1/ship/cfg/tr1/strings.json5', 'data/tr2/ship/cfg/tr2/strings.json5']) {
    const doc = show('trx-1.3', path);
    if (doc && doc.game_strings) Object.assign(oldIds, doc.game_strings);
}
const then = strings('trx-1.4', ['data/common/ship/cfg/base_strings.json5', 'data/tr1/ship/cfg/tr1/strings.json5', 'data/tr2/ship/cfg/tr2/strings.json5']);
const now = strings('HEAD', ['data/trx/ship/cfg/base_strings.json5', 'data/trx/ship/games/tr1/strings.json5', 'data/trx/ship/games/tr2/strings.json5', 'data/trx/ship/games/tr3/strings.json5']);
const byText = (table) => {
    const out = {};
    for (const [path, text] of Object.entries(table)) (out[text] ??= []).push(path);
    return out;
};
const thenByText = byText(then);
const nowByText = byText(now);
const ids = {};
for (const [id, text] of Object.entries(oldIds)) {
    // The path 1.4 gave the same text, if it still exists; else the text now.
    const candidates = (thenByText[text] ?? []).filter((p) => p in now);
    const path = candidates[0] ?? (nowByText[text] ?? [])[0];
    if (path) ids[id] = path;
}

const lines = [
    "// Generated by scripts/extract-history.mjs from TRX's git history.",
    '// Do not edit; run the script again against a newer TRX.',
    '',
    '/** Git blob ids, cut to 16 hex digits, of the files TRX has shipped, by name. */',
    'export const STOCK_BLOBS: Record<string, string[]> = {',
    ...Object.keys(blobs).sort().map((n) => `    ${JSON.stringify(n)}: ${JSON.stringify([...blobs[n]].sort())},`),
    '};',
    '',
    '/** TRX 1.3 string ids, by the path the current strings give their text. */',
    'export const GAME_STRING_IDS: Record<string, string> = {',
    ...Object.keys(ids).sort().map((id) => `    ${JSON.stringify(id)}: ${JSON.stringify(ids[id])},`),
    '};',
    '',
];
writeFileSync('client/src/converter/history.generated.ts', lines.join('\n'));
const total = Object.values(blobs).reduce((n, s) => n + s.size, 0);
console.log(`stock files: ${Object.keys(blobs).length} names, ${total} versions; string ids: ${Object.keys(ids).length} of ${Object.keys(oldIds).length}`);
